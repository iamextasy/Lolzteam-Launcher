/**
 * The JavaScript the patcher writes into an extension. Electron 33 implements only part of the `chrome.*` API:
 * `storage.sync` exists but every call fails, and `windows`, `notifications`, `contextMenus`, `cookies`,
 * `webNavigation`, `offscreen`, `permissions` are simply absent in a service worker — so the first
 * `chrome.windows.onBoundsChanged.addListener(…)` throws and the rest of the extension's startup never runs.
 * These shims fill the holes with inert stand-ins. They only ever define what is missing, never replace
 * what works — `storage.sync` and `storage.managed` are the exception, being present but broken.
 */

/** First line of every file the patcher generates — how a second patch recognises its own work. */
export const GENERATED_MARK = '// lzt-compat: generated by Lolzteam Launcher';

/** `sync` becomes `local` (verified on Electron 33); `managed` an empty read-only area, as Chrome shows with no policy. */
const STORAGE_PART = `
  var force = function (obj, name, value) {
    try { obj[name] = value; } catch (e) {}
    if (obj[name] !== value) {
      try { Object.defineProperty(obj, name, { value: value, configurable: true, writable: true, enumerable: true }); } catch (e) {}
    }
  };
  var noop = function () {};
  var event = function () {
    return {
      addListener: noop,
      removeListener: noop,
      hasListener: function () { return false; },
      hasListeners: function () { return false; },
    };
  };
  // Both calling styles: a trailing callback (called asynchronously, as Chrome does) and the returned promise.
  var method = function (answer) {
    return function () {
      var args = Array.prototype.slice.call(arguments);
      var cb = typeof args[args.length - 1] === 'function' ? args.pop() : null;
      var value;
      try { value = typeof answer === 'function' ? answer.apply(null, args) : answer; } catch (e) { value = undefined; }
      if (cb) Promise.resolve().then(function () { cb(value); });
      return Promise.resolve(value);
    };
  };
  var st = c.storage;
  if (st && st.local) {
    force(st, 'sync', st.local);
    force(st, 'managed', {
      get: method(function () { return {}; }),
      getBytesInUse: method(function () { return 0; }),
      getKeys: method(function () { return []; }),
      set: method(undefined),
      remove: method(undefined),
      clear: method(undefined),
      setAccessLevel: method(undefined),
      onChanged: event(),
    });
  }
`;

/** Everything else, for the service worker, an MV2 background page, the popup and the options page. */
const API_PART = `
  var put = function (obj, name, value) {
    if (!obj) return undefined;
    try {
      if (obj[name] === undefined) force(obj, name, value);
      return obj[name];
    } catch (e) {
      return undefined;
    }
  };
  var fill = function (obj, members) {
    if (obj) for (var k in members) put(obj, k, members[k]);
    return obj;
  };
  var ns = function (name) { return put(c, name, {}); };
  var manifest = {};
  try { manifest = (c.runtime && c.runtime.getManifest && c.runtime.getManifest()) || {}; } catch (e) {}

  // Opening a page is the one thing a stand-in can still do: through window.open where there is a window
  // (the launcher's guards decide what opens), and clients.openWindow in a worker, which may well refuse.
  var open = function (urls) {
    (Array.isArray(urls) ? urls : [urls]).forEach(function (u) {
      if (typeof u !== 'string' || !u) return;
      var url;
      try { url = new URL(u, g.location && g.location.href); } catch (e) { return; }
      if (!/^(https?|chrome-extension):$/.test(url.protocol)) return;
      var href = url.href;
      try {
        if (typeof g.open === 'function') g.open(href, '_blank');
        else if (g.clients && typeof g.clients.openWindow === 'function') g.clients.openWindow(href).catch(noop);
      } catch (e) {}
    });
  };
  var none = function () { return undefined; };
  var nothing = function () { return null; };
  var empty = function () { return []; };
  var no = function () { return false; };
  var win = function () {
    return { id: -1, focused: true, top: 0, left: 0, width: 0, height: 0, incognito: false,
      type: 'normal', state: 'normal', alwaysOnTop: false, tabs: [] };
  };
  var tab = function (props) {
    return { id: -1, index: -1, windowId: -1, url: props && props.url, active: true, pinned: false,
      highlighted: false, incognito: false, selected: false, discarded: false, autoDiscardable: true, groupId: -1 };
  };

  fill(ns('windows'), {
    WINDOW_ID_NONE: -1,
    WINDOW_ID_CURRENT: -2,
    get: method(win),
    getCurrent: method(win),
    getLastFocused: method(win),
    getAll: method(empty),
    create: method(function (opts) { open(opts && opts.url); return win(); }),
    update: method(win),
    remove: method(none),
    onCreated: event(),
    onRemoved: event(),
    onFocusChanged: event(),
    onBoundsChanged: event(),
  });

  fill(ns('tabs'), {
    TAB_ID_NONE: -1,
    create: method(function (props) { open(props && props.url); return tab(props); }),
    update: method(none),
    get: method(none),
    getCurrent: method(none),
    remove: method(none),
    query: method(empty),
    onCreated: event(),
    onUpdated: event(),
    onActivated: event(),
    onRemoved: event(),
    onReplaced: event(),
    onHighlighted: event(),
    onMoved: event(),
    onAttached: event(),
    onDetached: event(),
    onZoomChange: event(),
  });

  var notificationId = 0;
  fill(ns('notifications'), {
    TemplateType: { BASIC: 'basic', IMAGE: 'image', LIST: 'list', PROGRESS: 'progress' },
    PermissionLevel: { GRANTED: 'granted', DENIED: 'denied' },
    create: method(function (id) { return typeof id === 'string' && id ? id : 'lzt-' + ++notificationId; }),
    update: method(no),
    clear: method(no),
    getAll: method(function () { return {}; }),
    getPermissionLevel: method(function () { return 'denied'; }),
    onClicked: event(),
    onClosed: event(),
    onButtonClicked: event(),
    onPermissionLevelChanged: event(),
    onShowSettings: event(),
  });

  var menuId = 0;
  fill(ns('contextMenus'), {
    ACTION_MENU_TOP_LEVEL_LIMIT: 6,
    ContextType: { ALL: 'all', PAGE: 'page', FRAME: 'frame', SELECTION: 'selection', LINK: 'link',
      EDITABLE: 'editable', IMAGE: 'image', VIDEO: 'video', AUDIO: 'audio', LAUNCHER: 'launcher',
      BROWSER_ACTION: 'browser_action', PAGE_ACTION: 'page_action', ACTION: 'action' },
    ItemType: { NORMAL: 'normal', CHECKBOX: 'checkbox', RADIO: 'radio', SEPARATOR: 'separator' },
    // The one call that answers synchronously: it returns the new item's id.
    create: function (props, cb) {
      var id = props && props.id !== undefined ? props.id : ++menuId;
      if (typeof cb === 'function') Promise.resolve().then(function () { cb(); });
      return id;
    },
    update: method(none),
    remove: method(none),
    removeAll: method(none),
    onClicked: event(),
  });

  fill(ns('cookies'), {
    get: method(nothing),
    getAll: method(empty),
    set: method(nothing),
    remove: method(nothing),
    getAllCookieStores: method(empty),
    onChanged: event(),
  });

  fill(ns('webNavigation'), {
    getFrame: method(nothing),
    getAllFrames: method(empty),
    onBeforeNavigate: event(),
    onCommitted: event(),
    onDOMContentLoaded: event(),
    onCompleted: event(),
    onErrorOccurred: event(),
    onCreatedNavigationTarget: event(),
    onReferenceFragmentUpdated: event(),
    onTabReplaced: event(),
    onHistoryStateUpdated: event(),
  });

  fill(ns('offscreen'), {
    Reason: { TESTING: 'TESTING', AUDIO_PLAYBACK: 'AUDIO_PLAYBACK', IFRAME_SCRIPTING: 'IFRAME_SCRIPTING',
      DOM_SCRAPING: 'DOM_SCRAPING', BLOBS: 'BLOBS', DOM_PARSER: 'DOM_PARSER', USER_MEDIA: 'USER_MEDIA',
      DISPLAY_MEDIA: 'DISPLAY_MEDIA', WEB_RTC: 'WEB_RTC', CLIPBOARD: 'CLIPBOARD', LOCAL_STORAGE: 'LOCAL_STORAGE',
      WORKERS: 'WORKERS', BATTERY_STATUS: 'BATTERY_STATUS', MATCH_MEDIA: 'MATCH_MEDIA', GEOLOCATION: 'GEOLOCATION' },
    createDocument: method(none),
    closeDocument: method(none),
    hasDocument: method(no),
  });

  // What the manifest declared is what the extension has; nothing optional is ever granted here.
  var declared = (manifest.permissions || []).filter(function (p) { return typeof p === 'string'; });
  var origins = (manifest.host_permissions || []).concat(declared.filter(function (p) {
    return p === '<all_urls>' || p.indexOf('://') > 0;
  }));
  var allSites = origins.indexOf('<all_urls>') >= 0 || origins.indexOf('*://*/*') >= 0;
  var holds = function (req) {
    req = req || {};
    return (req.permissions || []).every(function (p) { return declared.indexOf(p) >= 0; }) &&
      (req.origins || []).every(function (o) { return allSites || origins.indexOf(o) >= 0; });
  };
  fill(ns('permissions'), {
    contains: method(holds),
    request: method(holds),
    remove: method(no),
    getAll: method(function () { return { permissions: declared.slice(), origins: origins.slice() }; }),
    onAdded: event(),
    onRemoved: event(),
  });

  var action = function () {
    return {
      setBadgeText: method(none), setBadgeBackgroundColor: method(none), setBadgeTextColor: method(none),
      setTitle: method(none), setIcon: method(none), setPopup: method(none),
      enable: method(none), disable: method(none), show: method(none), hide: method(none),
      getBadgeText: method(function () { return ''; }), getTitle: method(function () { return ''; }),
      getPopup: method(function () { return ''; }),
      getBadgeBackgroundColor: method(function () { return [0, 0, 0, 0]; }),
      getBadgeTextColor: method(function () { return [0, 0, 0, 0]; }),
      getUserSettings: method(function () { return { isOnToolbar: false }; }),
      isEnabled: method(function () { return true; }),
      openPopup: method(none),
      onClicked: event(),
      onUserSettingsChanged: event(),
    };
  };
  // Only the namespace this manifest version has: code that picks \`chrome.browserAction || chrome.action\` must
  // not be handed a stand-in in place of the real one.
  if (manifest.manifest_version === 3) fill(ns('action'), action());
  else {
    if (manifest.browser_action) fill(ns('browserAction'), action());
    if (manifest.page_action) fill(ns('pageAction'), action());
  }

  fill(ns('commands'), { getAll: method(empty), onCommand: event(), onChanged: event() });
  fill(ns('idle'), {
    queryState: method(function () { return 'active'; }),
    setDetectionInterval: noop,
    getAutoLockDelay: method(function () { return 0; }),
    onStateChanged: event(),
  });

  var rt = c.runtime;
  fill(rt, {
    openOptionsPage: method(function () {
      var page = (manifest.options_ui && manifest.options_ui.page) || manifest.options_page;
      if (page && rt.getURL) open(rt.getURL(page));
    }),
    setUninstallURL: method(none),
    onInstalled: event(),
    onStartup: event(),
    onSuspend: event(),
    onSuspendCanceled: event(),
    onUpdateAvailable: event(),
    onRestartRequired: event(),
  });
`;

const wrap = (body: string): string => `${GENERATED_MARK}
(function () {
  'use strict';
  var g = typeof globalThis !== 'undefined' ? globalThis : self;
  var c = g.chrome;
  if (!c || (typeof c !== 'object' && typeof c !== 'function')) return;
  try {${body}
  } catch (e) {}
})();
`;

/** For content scripts: only storage — they get no other extension API to begin with. */
export const CONTENT_SHIM_JS = wrap(STORAGE_PART);

/** For the background (worker or page) and extension pages. Also loads as an ES module: no imports, strict. */
export const API_SHIM_JS = wrap(STORAGE_PART + API_PART);

/**
 * The worker the manifest points at instead of the extension's own: the shim first, then the original. It sits in
 * the original's folder, because a classic worker resolves `importScripts('relative.js')` against the worker's
 * own URL — moved elsewhere, every relative import inside the original would break.
 */
export const serviceWorkerWrapper = (
  originalFileName: string,
  shimPath: string,
  isModule: boolean,
): string => {
  const original = JSON.stringify(`./${encodeURIComponent(originalFileName)}`);
  const shim = JSON.stringify(`/${shimPath}`);
  return isModule
    ? `${GENERATED_MARK}\nimport ${shim};\nimport ${original};\n`
    : `${GENERATED_MARK}\nimportScripts(${shim});\nimportScripts(${original});\n`;
};
